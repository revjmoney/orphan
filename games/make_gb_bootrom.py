"""Orphan's own Game Boy boot ROM (256 bytes) -> orphan_gb/brom.v. by JMSCNC, makers of RotatoCAM. GPL-2.0-or-later.
Not Nintendo's: no logo, no checks. It only leaves the CPU and the chips the way games expect after a real boot,
then switches itself off with its last instruction at 0x00FE, so the next instruction is the cart's at 0x0100.
    py -3 make_gb_bootrom.py"""
import os

code = bytes([
    0x31, 0xFE, 0xFF,        # 0000 LD SP,$FFFE
    0x3E, 0x80, 0xE0, 0x26,  # 0003 LD A,$80 ; LDH ($26),A   sound on (NR52)
    0x3E, 0x77, 0xE0, 0x24,  # 0007 LD A,$77 ; LDH ($24),A   full volume both sides (NR50)
    0x3E, 0xF3, 0xE0, 0x25,  # 000B LD A,$F3 ; LDH ($25),A   channel routing (NR51)
    0x3E, 0xFC, 0xE0, 0x47,  # 000F LD A,$FC ; LDH ($47),A   background palette (BGP)
    0x3E, 0x91, 0xE0, 0x40,  # 0013 LD A,$91 ; LDH ($40),A   screen on, background on (LCDC)
    0x01, 0xB0, 0x01,        # 0017 LD BC,$01B0
    0xC5, 0xF1,              # 001A PUSH BC ; POP AF          AF = $01B0 (A = 1: "original Game Boy")
    0x01, 0x13, 0x00,        # 001C LD BC,$0013
    0x11, 0xD8, 0x00,        # 001F LD DE,$00D8
    0x21, 0x4D, 0x01,        # 0022 LD HL,$014D
    0xC3, 0xFE, 0x00,        # 0025 JP $00FE
])
rom = bytearray(code + bytes(256 - len(code)))
rom[0xFE:0x100] = bytes([0xE0, 0x50])            # 00FE LDH ($50),A   boot ROM off (A = 1) -> PC = $0100
init = '\n'.join('        brom_array[%d] = 8\'h%02X;' % (i, b) for i, b in enumerate(rom) if b)
v = '''`timescale 1ns / 1ps
// Orphan's own Game Boy boot ROM (generated by make_gb_bootrom.py; replaces VerilogBoy's brom.v, which loads
// Nintendo's boot ROM from a file). by JMSCNC, makers of RotatoCAM. GPL-2.0-or-later.
module brom(
    input [7:0] a,
    output [7:0] d
    );
    reg [7:0] brom_array [0:255];
    integer i;
    initial begin
        for (i = 0; i < 256; i = i + 1) brom_array[i] = 8'h00;
%s
    end
    assign d = brom_array[a];
endmodule
''' % init
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'orphan_gb', 'brom.v'), 'w').write(v)
print('brom.v: %d code bytes' % len(code))
