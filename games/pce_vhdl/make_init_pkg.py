"""Turn the MiSTer TurboGrafx16 core's two .mif memory images (the PSG volume table, the VCE palette at power-on)
into a VHDL package, so GHDL can build them into the Verilog netlist (Altera's .mif files are Quartus-only).
    py -3 make_init_pkg.py   ->  pce_init_pkg.vhd
by JMSCNC, makers of RotatoCAM. GPL-3.0-or-later."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))


def mif(name, depth, width):
    vals = [0] * depth
    for a, v in re.findall(r'^\s*([0-9A-Fa-f]+)\s*:\s*([0-9A-Fa-f]+)\s*;', open(os.path.join(HERE, name)).read(), re.M):
        vals[int(a, 16)] = int(v, 16)
    nh = (width + 3) // 4
    return ',\n'.join('    ' + ', '.join('"%s"' % format(v, '0%db' % width) for v in vals[i:i + 8])
                      for i in range(0, depth, 8))


out = ['-- Generated by make_init_pkg.py from voltab.mif and huc6260_palette_init.mif (MiSTer TurboGrafx16 core).',
       'library ieee;', 'use ieee.std_logic_1164.all;', '', 'package pce_init_pkg is',
       '  type voltab_t is array(0 to 4095) of std_logic_vector(23 downto 0);',
       '  type paltab_t is array(0 to 511) of std_logic_vector(8 downto 0);',
       '  constant VOLTAB : voltab_t := (', mif('voltab.mif', 4096, 24), '  );',
       '  constant PALTAB : paltab_t := (', mif('huc6260_palette_init.mif', 512, 9), '  );',
       'end package;', '']
open(os.path.join(HERE, 'pce_init_pkg.vhd'), 'w').write('\n'.join(out))
print('wrote pce_init_pkg.vhd')
